#!/usr/bin/env bash
# Sets openGym up on a fresh Ubuntu/Debian VPS with HTTPS, then keeps it running.
#
#   sudo ./deploy/setup-vps.sh            first install (or re-run safely)
#   sudo ./deploy/setup-vps.sh lock       after creating your profile: invite-only signup
#   sudo ./deploy/setup-vps.sh update     pull the newest release and restart
#   sudo ./deploy/setup-vps.sh backup     write a backup of ./data now
#
# Hostname: OPENGYM_HOST=gym.example.com to use your own domain (its DNS must point at this
# server). Without it, the server's public IP is used as <a-b-c-d>.sslip.io, which needs no
# domain and still gets a real certificate.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
BACKUP_DIR="${BACKUP_DIR:-/var/backups/opengym}"

compose() { docker compose -f docker-compose.yml -f deploy/compose.vps.yml "$@"; }

need_root() {
  if [ "$(id -u)" -ne 0 ]; then echo "Run with sudo." >&2; exit 1; fi
}

# Sets KEY=VALUE in .env, replacing an active line or appending one.
set_env() {
  local key="$1" value="$2"
  if grep -qE "^${key}=" .env; then
    sed -i -E "s|^${key}=.*|${key}=${value}|" .env
  else
    echo "${key}=${value}" >> .env
  fi
}

install_docker() {
  if command -v docker >/dev/null && docker compose version >/dev/null 2>&1; then return; fi
  echo "==> Installing Docker"
  curl -fsSL https://get.docker.com | sh
  systemctl enable --now docker
}

open_firewall() {
  echo "==> Opening ports 80 and 443 on this machine"
  # Oracle Cloud's Ubuntu images ship iptables rules that reject everything but SSH.
  if command -v iptables >/dev/null && iptables -S INPUT 2>/dev/null | grep -q -- '-j REJECT'; then
    for p in 80 443; do
      iptables -C INPUT -p tcp --dport "$p" -j ACCEPT 2>/dev/null \
        || iptables -I INPUT -p tcp --dport "$p" -j ACCEPT
    done
    iptables -C INPUT -p udp --dport 443 -j ACCEPT 2>/dev/null \
      || iptables -I INPUT -p udp --dport 443 -j ACCEPT
    if command -v netfilter-persistent >/dev/null; then netfilter-persistent save; fi
  fi
  if command -v ufw >/dev/null && ufw status | grep -q 'Status: active'; then
    ufw allow 80/tcp && ufw allow 443/tcp && ufw allow 443/udp
  fi
}

pick_host() {
  if [ -n "${OPENGYM_HOST:-}" ]; then echo "$OPENGYM_HOST"; return; fi
  local existing
  existing="$(grep -E '^RP_ID=' .env 2>/dev/null | cut -d= -f2 || true)"
  if [ -n "$existing" ] && [ "$existing" != "localhost" ]; then echo "$existing"; return; fi
  local ip
  ip="$(curl -4 -fsS https://api.ipify.org)"
  echo "${ip//./-}.sslip.io"
}

# Until your profile exists, signup is open and the first profile becomes admin. A password on
# the whole site (shown only on this console) keeps anyone else from claiming it first.
gate_site() {
  local pass hash
  pass="$(openssl rand -base64 18)"
  hash="$(docker run --rm caddy:2 caddy hash-password --plaintext "$pass")"
  (umask 077; cat > deploy/Caddyfile.setup <<EOF
# Generated by setup-vps.sh; removed by \`setup-vps.sh lock\`.
{\$OPENGYM_HOST} {
	basic_auth {
		setup $hash
	}
	reverse_proxy web:80 {
		header_up CF-Connecting-IP {remote_host}
	}
}
EOF
  )
  # Caddy runs as root in its container, so owner-only is still readable there.
  set_env CADDYFILE Caddyfile.setup
  SETUP_PASS="$pass"
}

install_backup_cron() {
  cat > /etc/cron.d/opengym-backup <<EOF
# Daily openGym backup at 03:30, keeping the newest 14.
30 3 * * * root $ROOT/deploy/setup-vps.sh backup >/dev/null 2>&1
EOF
}

cmd_install() {
  need_root
  install_docker
  open_firewall
  [ -f .env ] || cp .env.example .env

  local host
  host="$(pick_host)"
  echo "==> Hostname: $host"
  set_env RP_ID "$host"
  set_env ORIGIN "https://$host"
  # Only Caddy is public; the web container listens on the loopback for it.
  set_env WEB_PORT "127.0.0.1:8080"
  set_env FIRST_USER_ADMIN 1
  set_env ALLOW_GUEST 0
  # Lets you sign in where passkeys don't work (some Linux browsers) and recover a lost one.
  set_env PASSWORD_LOGIN 1

  mkdir -p data coach-auth caddy-data caddy-config
  compose pull
  SETUP_PASS=""
  grep -qE '^INVITE_ONLY=1' .env || gate_site
  compose up -d
  install_backup_cron

  echo
  echo "openGym is starting at:  https://$host"
  echo "The certificate can take a minute on first start."
  if [ -n "$SETUP_PASS" ]; then
    echo "Until you lock it, the site asks for a login first:"
    echo "  user: setup    password: $SETUP_PASS"
    echo "Then:"
    echo "  1. Open the address, log in with the above, and create your profile (it becomes the admin)."
    echo "  2. Run: sudo ./deploy/setup-vps.sh lock   (invite-only signup, removes the login)."
  fi
}

cmd_lock() {
  need_root
  set_env INVITE_ONLY 1
  set_env CADDYFILE Caddyfile
  # Caddy's mount changed, so it is recreated; api picks up INVITE_ONLY.
  compose up -d
  rm -f deploy/Caddyfile.setup
  echo "Signup is now invite-only. Make invite codes in Settings → Account → Admin dashboard."
}

cmd_update() {
  need_root
  # As the checkout's owner: git refuses a repo owned by someone else when run as root.
  sudo -u "$(stat -c %U .)" git pull --ff-only
  compose pull
  compose up -d
  docker image prune -f >/dev/null
}

cmd_backup() {
  need_root
  # Sessions' signing key and password hashes are in data/: root-only.
  install -d -m 700 "$BACKUP_DIR"
  (umask 077; tar czf "$BACKUP_DIR/opengym-$(date +%F).tar.gz" data/)
  ls -1t "$BACKUP_DIR"/opengym-*.tar.gz | tail -n +15 | xargs -r rm --
  echo "Backup written to $BACKUP_DIR"
}

case "${1:-install}" in
  install) cmd_install ;;
  lock)    cmd_lock ;;
  update)  cmd_update ;;
  backup)  cmd_backup ;;
  *) echo "Usage: $0 [install|lock|update|backup]" >&2; exit 1 ;;
esac
